export const getStatusPillClass = (status, size = "sm") => {
  const tones = {
    pending: { pill: styles.cls089, dot: styles.cls090 },
    reviewed: { pill: styles.cls091, dot: styles.cls092 },
    resolved: { pill: styles.cls093, dot: styles.cls094 },
    default: { pill: styles.cls095, dot: styles.cls096 },
  };
  const tone = tones[status] || tones.default;
  return {
    pill: `${styles.cls086} ${size === "sm" ? styles.cls087 : styles.cls088} ${tone.pill}`.trim(),
    dot: `${styles.cls097} ${tone.dot}`.trim(),
  };
};

